    /** قائمة المناطق للاختيار */
    public static function areas(): array
    {
        return array_map(fn ($a) => [
            'title' => $a['title'],
            'sop'   => $a['sop'],
            'dept'  => $a['dept'],
            'count' => count($a['items']),
        ], self::AREAS);
    }

    /** بنود منطقة: [المتطلب، التصنيف] */
    public static function items(string $area): array
    {
        return self::AREAS[$area]['items'] ?? [];
