    /**
     * التحقق من رقم GLN (١٣ رقماً) برقم التحقق الأخير حسب GS1
     */
    public static function validGln(string $gln): bool
    {
        if (! preg_match('/^\d{13}$/', $gln)) {
            return false;
        }

        $sum = 0;
        // من اليمين بدون رقم التحقق: الأوزان ٣ ثم ١ بالتبادل
        for ($i = 11, $w = 3; $i >= 0; $i--, $w = $w === 3 ? 1 : 3) {
            $sum += (int) $gln[$i] * $w;
        }

        return (10 - $sum % 10) % 10 === (int) $gln[12];
    }
